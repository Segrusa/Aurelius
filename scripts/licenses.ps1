# Writes THIRD-PARTY-LICENSES.md: every third-party crate in the Windows, macOS
# and Linux builds, with its version, license and source, followed by the bundled
# mermaid script and the Flutter/Dart dependencies of the mobile app.
# Offline: uses Cargo.lock and the local registry. Run before a release
# (release.yml also ships it in the zip).
param([string]$Out = "THIRD-PARTY-LICENSES.md")
$ErrorActionPreference = "Stop"
Set-Location (Split-Path -Parent $PSScriptRoot)

# Only packages that are actually in the resolved graph of one of the platforms,
# minus our own crates. Offline first (local registry); a fresh machine (CI) may
# lack crates that the release build never downloaded, so fall back online.
$targets = "x86_64-pc-windows-msvc", "aarch64-apple-darwin", "x86_64-unknown-linux-gnu"
$all = @{}
foreach ($target in $targets) {
    $json = cargo metadata --format-version 1 --locked --offline --filter-platform $target 2>$null
    if ($LASTEXITCODE -ne 0) { $json = cargo metadata --format-version 1 --locked --filter-platform $target }
    if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed for $target" }
    $meta = $json | ConvertFrom-Json
    $used = @{}
    foreach ($node in $meta.resolve.nodes) { $used[$node.id] = $true }
    foreach ($p in $meta.packages) { if ($used[$p.id] -and $p.source) { $all["$($p.name) $($p.version)"] = $p } }
}
$packages = $all.Values | Sort-Object name, version

$lines = @(
    "# Third-party licenses",
    "",
    "Aurelius is built with the open-source crates below (Windows, macOS and Linux builds, from Cargo.lock).",
    "Each crate is distributed under the license(s) listed; the full texts are in each crate's source package.",
    "The Rust part is generated by ``scripts/licenses.ps1``; do not edit it by hand.",
    "",
    "## Summary",
    "",
    "| License | Crates |",
    "|---|---|"
)
$groups = $packages | Group-Object { if ($_.license) { $_.license } elseif ($_.license_file) { "see $($_.license_file)" } else { "UNKNOWN" } } | Sort-Object Count -Descending
foreach ($g in $groups) { $lines += "| $($g.Name) | $($g.Count) |" }
$lines += ""
$lines += "## Crates"
$lines += ""
$lines += "| Crate | Version | License | Source |"
$lines += "|---|---|---|---|"
foreach ($p in $packages) {
    $license = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { "UNKNOWN" }
    $source = if ($p.repository) { $p.repository } else { "crates.io/crates/$($p.name)" }
    $lines += "| $($p.name) | $($p.version) | $license | $source |"
}

# Mobile app: bundled script and Dart packages (direct dependencies; the
# transitive ones are in clients/mobile/pubspec.lock and are BSD-3-Clause or MIT).
$lines += ""
$lines += "## Mobile app"
$lines += ""
$lines += "Bundled in ``clients/mobile/assets/mermaid``: [mermaid](https://github.com/mermaid-js/mermaid) 12.2.0 (MIT), which carries its own bundled dependencies under permissive licenses."
$lines += ""
$lines += "Flutter/Dart dependencies of ``clients/mobile`` (direct):"
$lines += ""
$lines += "| Package | Version | License |"
$lines += "|---|---|---|"
$lock = Get-Content "clients/mobile/pubspec.lock" -Raw
foreach ($m in [regex]::Matches($lock, '(?m)^  (\w+):\r?\n    dependency: "direct main"[\s\S]*?version: "([^"]+)"')) {
    $name = $m.Groups[1].Value
    if ($name -eq "flutter") { continue }
    $lines += "| $name | $($m.Groups[2].Value) | $(switch ($name) { 'bloc_concurrency' {'MIT'} 'cupertino_icons' {'MIT'} 'equatable' {'MIT'} 'file_picker' {'MIT'} 'flutter_bloc' {'MIT'} 'uuid' {'MIT'} 'image_picker' {'Apache-2.0'} default {'BSD-3-Clause'} }) |"
}
$lines += ""
$lines += "The Flutter SDK itself is BSD-3-Clause. ``mobile_scanner`` uses Google ML Kit for barcode scanning on Android and iOS; ML Kit is a proprietary Google SDK distributed under its own terms (https://developers.google.com/ml-kit/terms), not an open-source license."
$lines -join "`n" | Out-File -Encoding utf8NoBOM $Out
"Wrote $Out ($($packages.Count) crates)"
$unknown = $packages | Where-Object { -not $_.license -and -not $_.license_file }
if ($unknown) { "No license field: " + (($unknown | ForEach-Object { $_.name }) -join ", ") }
$copyleft = $packages | Where-Object { $_.license -match "GPL" -and $_.license -notmatch " OR " }
if ($copyleft) { "Copyleft only (check): " + (($copyleft | ForEach-Object { "$($_.name) ($($_.license))" }) -join ", ") }
